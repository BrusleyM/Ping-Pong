namespace PingPong.GameFeel
{
    /// <summary>5x7 pixel font used by the cube scoreboard. '#' = lit pixel.</summary>
    public static class PixelFont
    {
        public const int Width = 5;
        public const int Height = 7;

        static readonly string[] Blank = { ".....", ".....", ".....", ".....", ".....", ".....", "....." };

        public static string[] Glyph(char ch)
        {
            switch (char.ToUpperInvariant(ch))
            {
                case 'A': return new[] { ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#" };
                case 'B': return new[] { "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####." };
                case 'C': return new[] { ".####", "#....", "#....", "#....", "#....", "#....", ".####" };
                case 'D': return new[] { "####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####." };
                case 'E': return new[] { "#####", "#....", "#....", "####.", "#....", "#....", "#####" };
                case 'F': return new[] { "#####", "#....", "#....", "####.", "#....", "#....", "#...." };
                case 'G': return new[] { ".####", "#....", "#....", "#..##", "#...#", "#...#", ".####" };
                case 'H': return new[] { "#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#" };
                case 'I': return new[] { "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####" };
                case 'J': return new[] { "..###", "...#.", "...#.", "...#.", "...#.", "#..#.", ".##.." };
                case 'K': return new[] { "#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#" };
                case 'L': return new[] { "#....", "#....", "#....", "#....", "#....", "#....", "#####" };
                case 'M': return new[] { "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#" };
                case 'N': return new[] { "#...#", "##..#", "#.#.#", "#.#.#", "#..##", "#...#", "#...#" };
                case 'O': return new[] { ".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###." };
                case 'P': return new[] { "####.", "#...#", "#...#", "####.", "#....", "#....", "#...." };
                case 'R': return new[] { "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#" };
                case 'S': return new[] { ".####", "#....", "#....", ".###.", "....#", "....#", "####." };
                case 'T': return new[] { "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.." };
                case 'U': return new[] { "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###." };
                case 'V': return new[] { "#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.." };
                case 'W': return new[] { "#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#" };
                case 'X': return new[] { "#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#" };
                case 'Y': return new[] { "#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.." };
                case '0': return new[] { ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###." };
                case '1': return new[] { "..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###." };
                case '2': return new[] { ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####" };
                case '3': return new[] { "####.", "....#", "....#", ".###.", "....#", "....#", "####." };
                case '4': return new[] { "...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#." };
                case '5': return new[] { "#####", "#....", "####.", "....#", "....#", "#...#", ".###." };
                case '6': return new[] { ".###.", "#....", "#....", "####.", "#...#", "#...#", ".###." };
                case '7': return new[] { "#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#..." };
                case '8': return new[] { ".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###." };
                case '9': return new[] { ".###.", "#...#", "#...#", ".####", "....#", "....#", ".###." };
                case '+': return new[] { ".....", "..#..", "..#..", "#####", "..#..", "..#..", "....." };
                case '-': return new[] { ".....", ".....", ".....", "#####", ".....", ".....", "....." };
                case ':': return new[] { ".....", "..#..", "..#..", ".....", "..#..", "..#..", "....." };
                case '!': return new[] { "..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#.." };
                default: return Blank;
            }
        }
    }
}
